#!/usr/bin/env python3
"""Deterministic operator-escalation gate (OPREQ ledger) — 2026-07-27.

Built after the operator found that `docs/ceo/cycle209-208a-operator-authorization-brief.md`
and `docs/ceo/cycle214-208a-amended-feasibility-result.md` contained a precise, real ask
("buy the complete Konak 2026/0003 tender packet") that was never actually surfaced to the
operator — it sat three files deep with no push notification and no durable, queryable
record of "this is still open."

This script is the ONLY thing that may:
  - decide whether an operator-request is genuinely new/changed and therefore worth a
    Telegram ping (dedup on a content fingerprint, not on presence alone);
  - mark a Telegram send as delivered (only after the Telegram API itself confirms
    `ok: true` — a non-erroring curl/urlopen call is not proof of delivery);
  - flip a request from OPEN to RESOLVED (requires a human-directive.md reference AND a
    type-specific DETERMINISTIC verification — a checksum-matched file on disk, a
    non-secret verification-log artifact, or a structured decision/authorization the
    OPERATOR wrote into human-directive.md — never a free-text claim the model wrote
    about itself; see verify_resolution() below);
  - regenerate the `## Awaiting Operator` section of consensus.md (a rendered projection,
    never a source of truth).

Source of truth for request content: memories/operator-requests.md (models append new
OPEN blocks here; this script never invents a request). Source of truth for
notification/dedup state: memories/.operator-requests-state.json — this file is written
ONLY by this script. Nothing in PROMPT.md ever instructs an agent to edit it directly;
agents that do so are violating policy, not exercising a legitimate write path.

Escalation-worthy types (the ONLY types that ever produce a Telegram notification or a
consensus.md projection entry) are documents, credentials, legal/financial decisions,
spend approval, external action beyond current authority, or a pending external
adjudication ruling — never a plain HOLD, UNKNOWN, research result, or informational
note. See ALLOWED_TYPES below.

Exit code is always 0 (never breaks the calling loop). All decisions are logged to
memories/operator-requests-audit.log.
"""
